/**
 * Builds test-shop/ground-truth.json from the data-dp-* attributes in the test
 * shop HTML. Only tools may read data-dp-*; detection code never does.
 *
 * Run with: npm run ground-truth   (Node >= 23.6 runs this .ts file directly)
 *
 * Fails (exit 1) if a label is unknown, an id is missing or duplicated, a
 * clean/ page has a non-benign label, an in-scope category has fewer than
 * MIN_PER_CATEGORY instances, or a page lacks the demo-store footer.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseHTML } from 'linkedom';
import { LABELS } from '../src/core/categories.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SHOP = join(ROOT, 'test-shop');
const OUT = join(SHOP, 'ground-truth.json');
const FOOTER = 'Demo store for testing DarkLens. Not a real shop.';
const MIN_PER_CATEGORY = 2;
const MAX_DESC = 90;

interface GroundTruthItem {
  page: string;
  id: string;
  label: string;
  labelId: number;
  tag: string;
  description: string;
}

function collapse(s: string | null | undefined): string {
  return (s ?? '').replace(/\s+/g, ' ').trim();
}

function truncate(s: string): string {
  return s.length > MAX_DESC ? s.slice(0, MAX_DESC - 1).trimEnd() + '…' : s;
}

/** Visible-ish text with a space at every element boundary (so <br> and spans don't glue words), skipping select options. */
function textOf(node: Node): string {
  if (node.nodeType === 3) return node.textContent ?? '';
  if (node.nodeType !== 1) return '';
  const tag = (node as Element).tagName.toLowerCase();
  if (tag === 'select' || tag === 'script' || tag === 'style') return ' ';
  return ' ' + Array.from(node.childNodes).map(textOf).join('') + ' ';
}

function describe(el: Element): string {
  const given = collapse(el.getAttribute('data-dp-desc'));
  if (given) return given;
  const tag = el.tagName.toLowerCase();
  const aria = collapse(el.getAttribute('aria-label'));
  const label = el.closest('label');
  const labelText = label ? collapse(textOf(label)) : '';
  if (tag === 'select') return truncate(`${aria || labelText || 'Unnamed'} dropdown`);
  const own = collapse(textOf(el));
  if (own) return truncate(own);
  if (labelText) return truncate(labelText);
  return aria || tag;
}

function findPages(): string[] {
  return readdirSync(SHOP, { recursive: true, encoding: 'utf8' })
    .filter((p) => p.endsWith('.html'))
    .map((p) => p.split(sep).join('/'))
    .sort();
}

function main(): void {
  const errors: string[] = [];
  const items: GroundTruthItem[] = [];
  const seenIds = new Map<string, string>();
  const pages = findPages();

  for (const page of pages) {
    const html = readFileSync(join(SHOP, page), 'utf8');
    const { document } = parseHTML(html);
    const isClean = page.startsWith('clean/');

    if (!collapse(document.body?.textContent).includes(FOOTER)) {
      errors.push(`${page}: footer sentence "${FOOTER}" is missing`);
    }

    for (const el of Array.from(document.querySelectorAll('[data-dp-label]'))) {
      const label = el.getAttribute('data-dp-label') ?? '';
      const id = el.getAttribute('data-dp-id') ?? '';
      const labelId = (LABELS as readonly string[]).indexOf(label);
      const where = `${page}: <${el.tagName.toLowerCase()}> ${id || '(no id)'}`;

      if (labelId < 0) errors.push(`${where}: unknown label "${label}"`);
      if (!id) errors.push(`${where}: missing data-dp-id`);
      else if (seenIds.has(id)) errors.push(`${where}: duplicate id, also on ${seenIds.get(id)}`);
      else seenIds.set(id, page);
      if (isClean && label !== 'benign') errors.push(`${where}: clean page has non-benign label "${label}"`);

      items.push({ page, id, label, labelId, tag: el.tagName.toLowerCase(), description: describe(el) });
    }

    for (const el of Array.from(document.querySelectorAll('[data-dp-id]:not([data-dp-label])'))) {
      errors.push(`${page}: data-dp-id "${el.getAttribute('data-dp-id')}" has no data-dp-label`);
    }
  }

  const counts: Record<string, number> = {};
  for (const label of LABELS) counts[label] = 0;
  for (const item of items) if (item.label in counts) counts[item.label]! += 1;

  for (const label of LABELS) {
    if (label !== 'benign' && counts[label]! < MIN_PER_CATEGORY) {
      errors.push(`category ${label}: ${counts[label]} instance(s), need at least ${MIN_PER_CATEGORY}`);
    }
  }

  const perPage: Record<string, { darkPatterns: number; benign: number }> = {};
  for (const page of pages) perPage[page] = { darkPatterns: 0, benign: 0 };
  for (const item of items) {
    const p = perPage[item.page]!;
    if (item.label === 'benign') p.benign += 1;
    else p.darkPatterns += 1;
  }

  const output = {
    note:
      'Generated by tools/build-ground-truth.ts from data-dp-* attributes. Do not edit by hand. ' +
      'Descendants of a labelled element inherit its label (use closest("[data-dp-label]")); unlabelled elements are not scored.',
    counts,
    pages: perPage,
    items,
  };
  writeFileSync(OUT, JSON.stringify(output, null, 2) + '\n');

  console.log(`Ground truth: ${items.length} labelled elements on ${pages.length} pages -> ${relative(ROOT, OUT)}\n`);
  console.log('  id  category                 count');
  LABELS.forEach((label, i) => {
    console.log(`  ${String(i).padStart(2)}  ${label.padEnd(24)} ${String(counts[label]).padStart(5)}`);
  });
  console.log('\n  page                     dark  benign');
  for (const page of pages) {
    const p = perPage[page]!;
    console.log(`  ${page.padEnd(24)} ${String(p.darkPatterns).padStart(4)}  ${String(p.benign).padStart(6)}`);
  }

  if (errors.length) {
    console.error(`\n${errors.length} problem(s):`);
    for (const e of errors) console.error(`  - ${e}`);
    process.exit(1);
  }
}

main();
